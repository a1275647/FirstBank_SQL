--              usp_MonitorData_Publish 在所有來源都完成後以短交易一次換入，
--              避免長時間鎖住正式表影響前端查詢。
--   參數：
--     @EXT_DATE        轉檔日期
--     @RetentionDays   STAGE 保留天數；開頭會清掉 EXT_DATE 早於 (@EXT_DATE - @RetentionDays) 的暫存資料，
--                      預設 7 天，留幾天供事後對照，避免暫存表無限長大
